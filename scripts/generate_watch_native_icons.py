"""Merge licensed, source-pinned Watch rasters with the complete portable inventory."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1];fonts=ROOT/'lib/PortableApps/fonts'
def read(name):
 s=(fonts/name).read_text()
 arrays={m[0]:m[1] for m in re.findall(r'(rpi_\w+)\[\] = \{([^}]+)\};',s)}
 return {m[0]:(m[1],m[2],m[3],arrays[m[3]]) for m in re.findall(r'\{"([^"]+)",(\d+),(\d+),(rpi_\w+)\}',s)}
rows=read('icons.inc');rows.update(read('watch-240-icons.inc'))
s='/* Generated by generate_watch_native_icons.py from icons.inc and watch-240-icons.inc.\n * Genuine Font Awesome OFL rasters; see SOURCES.json, watch-240-icons-source.json\n * and LICENSE-FontAwesome.txt. Higher-resolution Watch glyphs take precedence. */\n'
for w,h,ident,bits in rows.values():s+=f'static const uint8_t {ident}[] = {{{bits}}};\n'
s+='typedef struct { const char *name; uint8_t width,height; const uint8_t *bits; } rpi_glyph;\nstatic const rpi_glyph rpi_icons[] = {\n'
s+=',\n'.join('{"%s",%s,%s,%s}'%(name,*rows[name][:3]) for name in sorted(rows))+'\n};\n'
(fonts/'watch-native-icons.inc').write_text(s)
