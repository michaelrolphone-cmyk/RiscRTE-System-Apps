#!/usr/bin/env python3
"""Generate native Quick's 2x font masks from the existing licensed TTFs.

Pillow is an offline authoring dependency only. Runtime uses bounded integer
per-glyph rasterization; legacy 240x240 assets remain byte-for-byte unchanged.
"""
from pathlib import Path
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1] / 'lib/PortableApps'
alpha = []
lines = ['/* Generated by scripts/generate_quick_native_fonts.py. Licensed sources: quick_fonts/SOURCES.json. */']
for name, file, size, chars, tracking in [
    ('time', 'Orbitron-700.ttf', 13, '0123456789:-APM ', .78),
    ('percent', 'Orbitron-700.ttf', 10, '0123456789%!-', 0),
    ('label', 'Rajdhani-600.ttf', 10, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ -', .72),
    ('caption', 'Rajdhani-600.ttf', 9, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ -', .55),
    ('torch', 'Rajdhani-600.ttf', 11, 'TAP TO TURN OFF', 2.2),
]:
    font = ImageFont.truetype(str(ROOT / 'quick_fonts' / file), size * 8)
    glyphs = []
    for char in sorted(set(chars)):
        box = font.getbbox(char, anchor='ls')
        left, top = math.floor(box[0] / 4) - 1, math.floor(box[1] / 4) - 1
        right, bottom = math.ceil(box[2] / 4) + 1, math.ceil(box[3] / 4) + 1
        im = Image.new('L', ((right - left) * 4, (bottom - top) * 4))
        ImageDraw.Draw(im).text((-left * 4, -top * 4), char, fill=255, font=font, anchor='ls')
        im = im.resize((right - left, bottom - top), Image.Resampling.LANCZOS)
        offset = len(alpha)
        samples = list(im.tobytes())
        if len(samples) % 2:
            samples.append(0)
        alpha.extend(((samples[i] + 8) // 17) | (((samples[i + 1] + 8) // 17) << 4)
                     for i in range(0, len(samples), 2))
        advance = round((font.getlength(char) / 4 + tracking * 2) * 256)
        glyphs.append(f'{{{ord(char)},{left},{top},{im.width},{im.height},{advance},{offset}}}')
    lines.append('static const pqa_glyph pqa_native_' + name + '_glyphs[] = {\n' + ',\n'.join(glyphs) + '\n};')
lines.append('static const uint8_t pqa_native_alpha[] = {\n' + '\n'.join(
    ','.join(map(str, alpha[i:i + 28])) + ',' for i in range(0, len(alpha), 28)) + '\n};')
(ROOT / 'src/quick_native_fonts.inc').write_text('\n'.join(lines) + '\n')
print(f'{len(alpha)} packed 4-bit native glyph alpha bytes')
