#!/usr/bin/env python3
"""Copy exact existing NOVA glyph bytes/metrics into the opt-in 0/1/2 profile.

No font loading, rerasterization, resampling, or artwork editing is performed.
Run with --check to verify both generated files without changing them.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'lib/PortableApps/settings_fonts'
SOURCE_SHA256 = '8453a3f7c123799354a0ff4246dba420de2a612f421d6d9de9bf4c976073b449'


def generated_files():
    raw = (FONTS / 'text.inc').read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError('Original NOVA font changed; explicitly review the profile source first')
    source = raw.decode('ascii')
    arrays = re.findall(r'^static const uint8_t rps_(\d+)_(\d+)\[\]=\{[^\n]*\};$', source, re.M)
    expected = [(str(face), str(ch)) for face in range(6) for ch in range(32, 127)]
    if arrays != expected:
        raise ValueError('Original font must contain six ordered printable-ASCII faces')
    glyphs = re.findall(r'^\{[^\n]*,rps_(\d+)_(\d+)\},?$', source, re.M)
    if glyphs != expected:
        raise ValueError('Original metrics must contain the same six ordered faces')
    selected = []
    for line in source.splitlines():
        match = re.match(r'static const uint8_t rps_(\d+)_', line)
        if match and int(match[1]) < 3:
            selected.append(line)
    typedef = next(line for line in source.splitlines() if line.startswith('typedef struct'))
    rows = [line.rstrip(',') for line in source.splitlines()
            if re.match(r'^\{[^\n]*,rps_[012]_\d+\},?$', line)]
    assert len(selected) == len(rows) == 285
    text = '\n'.join([
        '#ifndef RISC_PORTABLE_SETTINGS_TEXT_INCLUDED',
        '#define RISC_PORTABLE_SETTINGS_TEXT_INCLUDED',
        '/* Generated by scripts/generate_nova_text_faces_012.py.',
        ' * RiscPortableSettingsText: exact original faces 0/1/2, ASCII 32..126.',
        ' * Orbitron/Rajdhani SIL OFL 1.1. See text-faces-012-source.json,',
        ' * SOURCES.json, LICENSE-Orbitron.txt, and LICENSE-Rajdhani.txt. */',
        *selected, typedef, 'static const rps_glyph rps_text[]={',
        ',\n'.join(rows), '};', '', '#endif', '',
    ])
    provenance = {
        'description': 'Exact byte-and-metric subset of RiscPortableSettingsText; no rerasterization.',
        'selection_macro': 'PORTABLE_NOVA_TEXT_FACES_012',
        'source': 'text.inc',
        'source_sha256': SOURCE_SHA256,
        'generator': 'scripts/generate_nova_text_faces_012.py',
        'faces': [0, 1, 2],
        'derived_face': {'6': 'Original face 0 at the unchanged 183/256 renderer scale'},
        'codepoints': {'first': 32, 'last': 126, 'count_per_face': 95},
        'glyph_count': 285,
        'license': 'SIL OFL 1.1',
        'source_attribution': 'SOURCES.json',
        'license_files': ['LICENSE-Orbitron.txt', 'LICENSE-Rajdhani.txt'],
        'subset_sha256': hashlib.sha256(text.encode('ascii')).hexdigest(),
    }
    return {'text-faces-012.inc': text,
            'text-faces-012-source.json': json.dumps(provenance, indent=2) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in generated_files().items():
        path = FONTS / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'{path.relative_to(ROOT)} is not the exact generated subset')
        else:
            path.write_text(content)
    print('Verified 285 exact NOVA glyph records and their generated provenance.' if args.check
          else 'Generated 285 exact NOVA glyph records and provenance.')


if __name__ == '__main__':
    main()
