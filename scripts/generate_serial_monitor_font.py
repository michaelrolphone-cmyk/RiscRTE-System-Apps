#!/usr/bin/env python3
"""Generate a fixed-cell ASCII terminal font from the existing OFL font input."""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'lib/PortableApps/quick_fonts/Rajdhani-600.ttf'
assert hashlib.sha256(source.read_bytes()).hexdigest() == 'bcffd70c330f38f97f49fbb41cad34a1628a7852c0e6d1d1418ebc162add3144'
font = ImageFont.truetype(str(source), 10)
lines = ['/* Generated by scripts/generate_serial_monitor_font.py from Rajdhani-600.ttf.',
         ' * SIL OFL 1.1: lib/PortableApps/paper_fonts/LICENSE-Rajdhani.txt. */',
         'static const unsigned char sm_font[95][12] = {']
for code in range(32,127):
    im=Image.new('L',(8,12)); draw=ImageDraw.Draw(im)
    box=font.getbbox(chr(code)); x=(8-(box[2]-box[0]))//2-box[0]
    draw.text((x,-2),chr(code),font=font,fill=255)
    rows=[sum((1<<(7-x)) for x in range(8) if im.getpixel((x,y))>=96) for y in range(12)]
    lines.append(' {'+','.join(str(n) for n in rows)+'}, /* '+str(code)+' */')
lines.append('};')
(ROOT/'Apps/serial_monitor_font.inc').write_text('\n'.join(lines)+'\n')
