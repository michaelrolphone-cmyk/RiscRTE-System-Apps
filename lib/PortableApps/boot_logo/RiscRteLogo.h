typedef bool (*riscrte_logo_rect_fn)(void *,int,int,int,int);
/* Matches the existing video logo's radius-4 coverage, at full coverage. */
static bool riscrte_logo_draw(void *context,riscrte_logo_rect_fn rect,int width,int height) {
 const int x=(width-240)/2,y=(height-320)/2;
 for(unsigned i=0;i<9;i++) {
  const int16_t *r=riscrte_logo_rectangles[i];
  const int w=r[2]*2,h=r[3]*2;
  for(int py=0;py<h;py++) {
   int inset=0;
   if(py<4 || py>=h-4) {
    int dy=py-(py<4?3:h-4);
    while((inset-3)*(inset-3)+dy*dy>16)inset++;
   }
   if(!rect(context,x+r[0]*2+inset,y+r[1]*2+py,w-inset*2,1))return false;
  }
 }
 int total=0;for(unsigned i=0;i<7;i++)total+=riscrte_wordmark_Widths[i];
 int left=(width-total)/2;
 for(unsigned i=0;i<7;i++) {
  for(int py=0;py<32;py++) {
   const uint32_t row=riscrte_wordmark_Rows[i][py];
   for(int px=0;px<riscrte_wordmark_Widths[i];) {
    if(!(row&(UINT32_C(1)<<px))){px++;continue;}
    int first=px++;
    while(px<riscrte_wordmark_Widths[i] && (row&(UINT32_C(1)<<px)))px++;
    if(!rect(context,left+first,y+244+py,px-first,1))return false;
   }
  }
  left+=riscrte_wordmark_Widths[i];
 }
 return true;
}
